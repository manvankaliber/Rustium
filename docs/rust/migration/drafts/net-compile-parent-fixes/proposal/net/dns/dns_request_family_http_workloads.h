struct HttpRow {
  std::string expected_query,body;
  bool post=false,hang=false;
  int status=200;
  std::string mime="application/dns-message";
  unsigned started=0,eof=0,matched=0;
};

// This is a typed-fixture I/O provider, not a DNS parser/attempt policy fallback.
// Expected query and response bytes were independently generated by each Api.
