#!/usr/bin/env python3
"""Deterministically generate mapping; --check fails closed on canonical drift."""
import argparse
import hashlib
import json
from pathlib import Path
import re
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
p.add_argument('--stamp', type=Path)
a = p.parse_args()
d = Path(__file__).resolve().parent
source = (d / 'http_status_code_list.h').read_bytes()
text = re.sub(r'//[^\n]*', '', source.decode())
entries = re.findall(r'HTTP_STATUS_ENUM_VALUE\(\s*([A-Z0-9_]+)\s*,\s*(\d+)\s*,\s*("(?:[^"\\]|\\.)*")\s*\)', text)
if not entries or len(entries) != text.count('HTTP_STATUS_ENUM_VALUE('):
    raise SystemExit('Unsupported canonical macro syntax')
if len({int(c) for _, c, _ in entries}) != len(entries):
    raise SystemExit('Duplicate numeric status')
lines = ['// Generated by http_status_code_generate.py; do not edit.',
         '// Canonical SHA256:',
         '// ' + hashlib.sha256(source).hexdigest(),
         '#[rustfmt::skip]',
         'pub fn reason(code: i32) -> Option<&\'static str> {', '    match code {']
for _, code, reason in entries:
    value = json.loads(reason)
    if not value.isascii():
        raise SystemExit('Review non-ASCII literal encoding before generating')
    lines.append(f'        {code} => Some({json.dumps(value)}),')
lines += ['        _ => None,', '    }', '}', '']
output = '\n'.join(lines)
target = d / 'http_status_code_generated.rs'
if a.check:
    if target.read_text() != output:
        raise SystemExit('Stale Rust mapping: run net/http/http_status_code_generate.py')
else:
    target.write_text(output, newline='\n')
if a.stamp:
    a.stamp.parent.mkdir(parents=True, exist_ok=True)
    a.stamp.write_text(hashlib.sha256(source).hexdigest() + '\n')
