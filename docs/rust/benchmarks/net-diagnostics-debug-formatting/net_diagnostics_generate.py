#!/usr/bin/env python3
"""Generate Rust policy tables from canonical Chromium declarations."""
from pathlib import Path
import argparse, hashlib, re
p=argparse.ArgumentParser(); p.add_argument('--check',action='store_true'); p.add_argument('--stamp',type=Path); a=p.parse_args()
d=Path(__file__).resolve().parent; source=(d/'load_flags_list.h').read_bytes()
t=re.sub(r'//[^\n]*','',source.decode()); entries=re.findall(r'LOAD_FLAG\(\s*([A-Z0-9_]+)\s*,\s*([^\)]+)\)',t)
if not entries or len(entries)!=t.count('LOAD_FLAG('): raise SystemExit('Unsupported load flag macro syntax')
rows=[]
for name,v in entries:
 v=v.strip()
 if v != '0' and not re.fullmatch(r'1\s*<<\s*\d+', v): raise SystemExit('Unsupported canonical flag value: '+v)
 value=0
 for shift in re.findall(r'1\s*<<\s*(\d+)',v): value |= 1 << int(shift)
 if v=='0': value=0
 rows.append((name,value))
lines=['// Generated by net_diagnostics_generate.py; do not edit.','// Canonical SHA256: '+hashlib.sha256(source).hexdigest(),'pub const LOAD_FLAGS: &[(u32, &str)] = &[']+[f'    ({v}u32, "{n}"),' for n,v in rows]+['];','']
out='\n'.join(lines); target=d/'net_diagnostics_load_flags_generated.rs'
if a.check:
 if not target.exists() or target.read_text()!=out: raise SystemExit('Stale generated flags: run net_diagnostics_generate.py')
else: target.write_text(out,newline='\n')
if a.stamp:
 a.stamp.parent.mkdir(parents=True,exist_ok=True)
 a.stamp.write_text(hashlib.sha256(source).hexdigest()+'\n')
