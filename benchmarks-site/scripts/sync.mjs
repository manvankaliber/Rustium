import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';

export const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const root = path.resolve(site, '..');
const check = process.argv.includes('--check');
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const html = fs.readFileSync(path.join(root, 'rust-performance.html'), 'utf8');
const block = html.match(/<script id="benchmark-data" type="application\/json">([\s\S]*?)<\/script>/);
if (!block) throw Error('Canonical benchmark-data block not found');
const data = JSON.parse(block[1]);
const start = html.indexOf("  const ink = '#1f1f1f'");
const end = html.indexOf("  document.getElementById('evidence-link').href=data.archive;", start);
if (start < 0 || end < 0) throw Error('Canonical engine boundaries changed. Review extraction before regenerating.');
const sourceBody = html.slice(start, end);
// Compatibility while the parent rolls out final_run to the standalone engine.
// This only changes run selection, never measured values or export rendering.
const oldSelection = "const run = metric.runs?.find(([id]) => id === 'final')?.[0] || metric.runs?.[0]?.[0];";
const body = sourceBody.replaceAll(oldSelection, "const run = metric.final_run || metric.runs?.find(([id]) => id === 'final')?.[0] || metric.runs?.[0]?.[0];");
for (const name of ['chart', 'exportSvg', 'generateVideo', 'mp4Video', 'averageResult', 'latestCases']) {
  if (!body.includes(`function ${name}(`)) throw Error(`Engine is missing ${name}`);
}
const engine = `// Generated by scripts/sync.mjs. Do not edit. Canonical engine SHA-256: ${sha(body)}\nexport function createEngine(data) {\n${body}\nreturn { metrics, chart, exportSvg, generateVideo, svgImage, saveBlob, download, averageResult, latestCases, selectedRows, speedup, relativeValue, relativeInterval, tip, number, signed };\n}\n`;
const outputs = new Map();
const add = (name, value) => outputs.set(name, Buffer.isBuffer(value) ? value : Buffer.from(value));
add('src/lib/generated/engine.js', engine);
add('src/lib/generated/data.json', JSON.stringify(data, null, 2) + '\n');

// Copy the archived evidence verbatim, preserving its relative paths. The
// canonical page's links then work both in the app and its offline companion.
const evidenceDir = path.join(root, 'docs/rust/benchmarks');
const evidence = {};
function collect(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a,b) => a.name.localeCompare(b.name, 'en'))) {
    const absolute = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) throw Error(`Symlink evidence is not allowed: ${absolute}`);
    if (entry.isDirectory()) collect(absolute);
    else {
      const relative = path.relative(root, absolute).replaceAll('\\', '/');
      const bytes = fs.readFileSync(absolute);
      evidence[relative] = sha(bytes);
      add(`static/evidence/${relative}`, bytes);
    }
  }
}
collect(evidenceDir);
const archives = [...new Set([data.archive, ...(data.additional_metrics || []).flatMap(m => Object.values(m.archives || {})), ...(data.additional_metrics || []).map(m => m.archive)].filter(Boolean))];
const archiveInfo = {};
for (const file of archives) {
  if (!evidence[file]) throw Error(`Archive missing from evidence: ${file}`);
  const archive = JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  const dateField = ['timestamp', 'recorded_at', 'date', 'snapshot_date'].find(k => typeof archive[k] === 'string' && /^\d{4}-\d{2}-\d{2}(?:$|T| )/.test(archive[k]));
  archiveInfo[file] = {
    date: dateField ? archive[dateField] : null,
    dateSource: dateField ? `${file}#${dateField}` : null,
    measurement: archive.metadata?.measurement || archive.measurement || null,
    sha256: evidence[file]
  };
}
const manifest = {
  schema: 1,
  canonical: 'rust-performance.html',
  canonical_sha256: sha(html),
  benchmark_data_sha256: sha(block[1]),
  engine_sha256: sha(body),
  engine_source_sha256: sha(sourceBody),
  extraction: 'From const ink through download(), before evidence-link DOM bootstrap. Prefer explicit metric.final_run in latestCases if the legacy selector is present. No math, rendering, or codec substitutions.',
  archives: archiveInfo,
  evidence
};
add('src/lib/generated/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
// The UI needs run context, not the hundreds of frozen-source hashes. Keep the
// complete verification manifest as an independently accessible evidence file.
const bridgeEvidence = (data.additional_metrics || []).flatMap(metric => [metric.bridge, ...Object.values(metric.run_context || {}).map(context => context.bridge)]).map(bridge => bridge?.evidence).filter(file => evidence[file]);
const runtime = { ...manifest, evidence: Object.fromEntries([...new Set([...archives, ...bridgeEvidence])].map(file => [file, evidence[file]])) };
add('src/lib/generated/context.json', JSON.stringify(runtime, null, 2) + '\n');
add('static/evidence/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
add('static/evidence/rust-performance.html', html);
const stale = [];
for (const [name, bytes] of outputs) {
  const destination = path.resolve(site, name);
  if (!destination.startsWith(site + path.sep)) throw Error('Output outside site');
  const equal = fs.existsSync(destination) && fs.readFileSync(destination).equals(bytes);
  if (!equal) {
    if (check) stale.push(name);
    else { fs.mkdirSync(path.dirname(destination), { recursive: true }); fs.writeFileSync(destination, bytes); }
  }
}
if (stale.length) throw Error(`Generated site data is stale (${stale.length} files). Run npm run sync.\n${stale.slice(0,10).join('\n')}`);
console.log(`${check ? 'Verified' : 'Synchronized'} canonical data, engine and ${Object.keys(evidence).length} evidence files. Data SHA-256 ${manifest.benchmark_data_sha256}`);
