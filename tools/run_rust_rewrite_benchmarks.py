class _WindowsProcessInformation(ctypes.Structure):
    # PROCESS_INFORMATION (processthreadsapi.h). Output storage must outlive
    # CreateProcessW even if Python delivers an interrupt as that call returns.
    _fields_ = [("hProcess", ctypes.c_void_p), ("hThread", ctypes.c_void_p),
                ("dwProcessId", ctypes.c_uint32), ("dwThreadId", ctypes.c_uint32)]


class _WindowsAffinityAPI:
    """Documented Win32 APIs, with pointer-sized masks and checked errors."""

    def __init__(self):
        from ctypes import wintypes

        self.kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        self.kernel32.SetProcessAffinityMask.argtypes = [wintypes.HANDLE, ctypes.c_size_t]
        self.kernel32.SetProcessAffinityMask.restype = wintypes.BOOL
        self.kernel32.GetProcessAffinityMask.argtypes = [
            wintypes.HANDLE, ctypes.POINTER(ctypes.c_size_t), ctypes.POINTER(ctypes.c_size_t)]
        self.kernel32.GetProcessAffinityMask.restype = wintypes.BOOL
        self.kernel32.ResumeThread.argtypes = [wintypes.HANDLE]
        self.kernel32.ResumeThread.restype = wintypes.DWORD

    def create_process(self, command, cwd, env, handles, inherited_handles, info):
        """Create suspended with only the stdio handle list inherited.

        Use caller-owned PROCESS_INFORMATION rather than a returned Python
        tuple: a KeyboardInterrupt at the native-call boundary must not lose
        the newly created child's handles. Popen already duplicated stdio.
        """
        from ctypes import wintypes

        class StartupInfo(ctypes.Structure):
            _fields_ = [("cb", wintypes.DWORD), ("lpReserved", wintypes.LPWSTR),
                        ("lpDesktop", wintypes.LPWSTR), ("lpTitle", wintypes.LPWSTR),
                        ("dwX", wintypes.DWORD), ("dwY", wintypes.DWORD),
                        ("dwXSize", wintypes.DWORD), ("dwYSize", wintypes.DWORD),
                        ("dwXCountChars", wintypes.DWORD), ("dwYCountChars", wintypes.DWORD),
                        ("dwFillAttribute", wintypes.DWORD), ("dwFlags", wintypes.DWORD),
                        ("wShowWindow", wintypes.WORD), ("cbReserved2", wintypes.WORD),
                        ("lpReserved2", ctypes.POINTER(ctypes.c_ubyte)),
                        ("hStdInput", wintypes.HANDLE), ("hStdOutput", wintypes.HANDLE),
                        ("hStdError", wintypes.HANDLE)]

        class StartupInfoEx(ctypes.Structure):
            _fields_ = [("StartupInfo", StartupInfo), ("lpAttributeList", ctypes.c_void_p)]

        initialize = self.kernel32.InitializeProcThreadAttributeList
        initialize.argtypes = [ctypes.c_void_p, wintypes.DWORD, wintypes.DWORD,
                               ctypes.POINTER(ctypes.c_size_t)]
        initialize.restype = wintypes.BOOL
        update = self.kernel32.UpdateProcThreadAttribute
        update.argtypes = [ctypes.c_void_p, wintypes.DWORD, ctypes.c_size_t, ctypes.c_void_p,
                           ctypes.c_size_t, ctypes.c_void_p, ctypes.POINTER(ctypes.c_size_t)]
        update.restype = wintypes.BOOL
        delete = self.kernel32.DeleteProcThreadAttributeList
        delete.argtypes = [ctypes.c_void_p]
        delete.restype = None
        create = self.kernel32.CreateProcessW
        create.argtypes = [wintypes.LPCWSTR, wintypes.LPWSTR, ctypes.c_void_p, ctypes.c_void_p,
                           wintypes.BOOL, wintypes.DWORD, ctypes.c_void_p, wintypes.LPCWSTR,
                           ctypes.POINTER(StartupInfoEx), ctypes.POINTER(_WindowsProcessInformation)]
        create.restype = wintypes.BOOL
        startup = StartupInfoEx()
        startup.StartupInfo.cb = ctypes.sizeof(startup)
        startup.StartupInfo.dwFlags = 0x00000100  # STARTF_USESTDHANDLES
        startup.StartupInfo.hStdInput, startup.StartupInfo.hStdOutput, startup.StartupInfo.hStdError = handles
        inherited = (wintypes.HANDLE * len(inherited_handles))(*inherited_handles)
        command_line = ctypes.create_unicode_buffer(subprocess.list2cmdline(command))
        for key, value in env.items():
            if not key or "=" in key[1:] or "\0" in key or "\0" in value:
                raise ValueError("Invalid benchmark environment entry")
        environment = ctypes.create_unicode_buffer("\0".join(
            key + "=" + value for key, value in sorted(env.items(), key=lambda item: item[0].upper())) + "\0\0")
        size = ctypes.c_size_t()
        # The documented sizing call fails with ERROR_INSUFFICIENT_BUFFER.
        initialize(None, 1, 0, ctypes.byref(size))
        if ctypes.get_last_error() != 122 or not size.value:
            raise ctypes.WinError(ctypes.get_last_error())
        attributes = ctypes.create_string_buffer(size.value)
        try:
            if not initialize(attributes, 1, 0, ctypes.byref(size)):
                raise ctypes.WinError(ctypes.get_last_error())
            startup.lpAttributeList = ctypes.addressof(attributes)
            # PROC_THREAD_ATTRIBUTE_HANDLE_LIST from processthreadsapi.h.
            if not update(attributes, 0, 0x00020002, inherited, ctypes.sizeof(inherited), None, None):
                raise ctypes.WinError(ctypes.get_last_error())
            # CREATE_SUSPENDED | CREATE_UNICODE_ENVIRONMENT | EXTENDED_STARTUPINFO_PRESENT.
            if not create(command[0], command_line, None, None, True, 0x00080404,
                          environment, os.fsdecode(cwd), ctypes.byref(startup), ctypes.byref(info)):
                raise ctypes.WinError(ctypes.get_last_error())
        finally:
            if startup.lpAttributeList:
                delete(attributes)

    def set_affinity(self, process_handle, mask):
        if not self.kernel32.SetProcessAffinityMask(process_handle, mask):
            raise ctypes.WinError(ctypes.get_last_error())

    def get_affinity(self, process_handle):
        process_mask, system_mask = ctypes.c_size_t(), ctypes.c_size_t()
        if not self.kernel32.GetProcessAffinityMask(
                process_handle, ctypes.byref(process_mask), ctypes.byref(system_mask)):
            raise ctypes.WinError(ctypes.get_last_error())
        return process_mask.value, system_mask.value

    def resume_thread(self, thread_handle):
        count = self.kernel32.ResumeThread(thread_handle)
        if count == 0xffffffff:
            raise ctypes.WinError(ctypes.get_last_error())
        if count != 1:
            raise RuntimeError("Owned primary thread had unexpected suspend count: " + str(count))
        return count


class _WindowsAffinityPopen(subprocess.Popen):
    """Restricted CPython Windows launch retaining CreateProcess's primary thread.

    CPython's normal _execute_child closes that handle before Popen returns.
    This override uses Popen's pipe preparation and the documented CreateProcessW,
    retaining the thread until affinity is verified. Caller-owned native output
    storage also retains handles on interruption. No thread discovery, process
    wrapper, or parent affinity changes.
    The private Popen interface is exercised on host and configured Python;
    this is deliberately not a general replacement for Popen's launch options.

    CREATE_SUSPENDED: https://learn.microsoft.com/windows/win32/procthread/process-creation-flags
    ResumeThread: https://learn.microsoft.com/windows/win32/api/processthreadsapi/nf-processthreadsapi-resumethread
    """

    def __init__(self, command, *, cwd, env, stdout, cpu):
        self._affinity_api = _WindowsAffinityAPI()
        self._requested_mask = 1 << cpu
        if not 0 < self._requested_mask < (1 << (ctypes.sizeof(ctypes.c_size_t) * 8)):
            raise ValueError("CPU index is outside the Windows affinity mask")
        super().__init__(command, cwd=cwd, env=env, stdout=stdout, stderr=subprocess.PIPE)

    def _execute_child(self, args, executable, preexec_fn, close_fds,
                       pass_fds, cwd, env, startupinfo, creationflags, shell,
                       p2cread, p2cwrite, c2pread, c2pwrite, errread, errwrite,
                       *unused_posix_options):
        import _winapi

        # Only the fixed options used by run_benchmark are supported. Fail
        # before creating a process if that contract changes.
        if (not isinstance(args, list) or not args or executable is not None or
                preexec_fn is not None or not close_fds or pass_fds or
                startupinfo is not None or creationflags or shell or
                -1 in (p2cread, c2pwrite, errwrite)):
            raise ValueError("Unsupported affinity benchmark launch options")
        command_line = subprocess.list2cmdline(args)
        sys.audit("subprocess.Popen", args[0], command_line, cwd, env)
        info = _WindowsProcessInformation()
        try:
            try:
                try:
                    self._affinity_api.create_process(
                        args, cwd, env, (int(p2cread), int(c2pwrite), int(errwrite)),
                        self._filter_handle_list([int(p2cread), int(c2pwrite), int(errwrite)]), info)
                finally:
                    self._close_pipe_fds(p2cread, p2cwrite, c2pread, c2pwrite, errread, errwrite)
                # Keep a raw handle under the run_benchmark owner's lifetime.
                # A temporary subprocess.Handle could close it if interrupted
                # between constructing that object and assigning the attribute.
                self._handle = info.hProcess
                self.pid = info.dwProcessId
                self._child_created = True
                self._affinity_api.set_affinity(info.hProcess, self._requested_mask)
                observed, system = self._affinity_api.get_affinity(info.hProcess)
                if observed != self._requested_mask:
                    raise RuntimeError(f"Child affinity mismatch: requested {self._requested_mask:#x}, "
                                       f"observed {observed:#x}")
                self.affinity = {
                    "requested_mask": self._requested_mask, "verified_process_mask": observed,
                    "observed_system_mask": system, "verified_before_resume": True,
                    "method": "CREATE_SUSPENDED; SetProcessAffinityMask; GetProcessAffinityMask; ResumeThread",
                    "process_id": info.dwProcessId, "primary_thread_id": info.dwThreadId,
                }
                self.affinity["previous_suspend_count"] = self._affinity_api.resume_thread(info.hThread)
            finally:
                if info.hThread:
                    _winapi.CloseHandle(info.hThread)
        except BaseException:
            if info.hProcess:
                # Handle ownership starts at CreateProcess, including failures
                # before Popen has adopted the handle. Never resume on failure.
                try:
                    _winapi.TerminateProcess(info.hProcess, 1)
                except OSError:
                    if _winapi.WaitForSingleObject(info.hProcess, 0) != _winapi.WAIT_OBJECT_0:
                        raise
                _winapi.WaitForSingleObject(info.hProcess, _winapi.INFINITE)
                self.returncode = _winapi.GetExitCodeProcess(info.hProcess)
                _winapi.CloseHandle(info.hProcess)
                self._handle = None
                self._child_created = False
            raise


def run_benchmark(command, *, cwd, env, stdout, cpu, timeout=None):
    """Run exactly command, returning (exit code, stderr bytes, affinity evidence).

    POSIX retains its existing post-spawn affinity placement, without claiming
    an observation or startup gating. Windows verifies before resuming.
    """
    process = None
    try:
        if os.name == "nt":
            # Register the owner before __init__: cancellation at its return
            # must also find and reap an already-resumed child.
            process = _WindowsAffinityPopen.__new__(_WindowsAffinityPopen)
            process.__init__(command, cwd=cwd, env=env, stdout=stdout, cpu=cpu)
            affinity = process.affinity
        else:
            process = subprocess.Popen(command, cwd=cwd, env=env, stdout=stdout,
                                       stderr=subprocess.PIPE)
            os.sched_setaffinity(process.pid, {cpu})
            affinity = {"requested_mask": 1 << cpu,
                        "verified_process_mask": None,
                        "verified_before_resume": False,
                        "method": "sched_setaffinity (after Popen; mask not queried; startup not gated)"}
        _, errors = process.communicate(timeout=timeout)
        return process.returncode, errors, affinity
    except BaseException:
        if process is not None and getattr(process, "_child_created", False):
            process.kill()
            process.wait()
        raise
    finally:
        if process is not None and getattr(process, "stderr", None) is not None:
            process.stderr.close()
        if os.name == "nt" and process is not None and getattr(process, "_handle", None):
            import _winapi
            _winapi.CloseHandle(process._handle)
            process._handle = None


